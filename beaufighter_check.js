  function removeEmojiLead(a){const first=a.firstElementChild;if(!first||first.tagName==='IMG')return;const t=(first.textContent||'').trim();if(t&&t.length<=3&&/^[^A-Za-z0-9]+$/.test(t))first.remove();}
  function styleThumb(img,compact){img.loading='lazy';img.style.width=compact?'132px':'100%';img.style.height=compact?'84px':'145px';img.style.objectFit='cover';img.style.display='block';img.style.borderRadius=compact?'3px':'0';img.style.flexShrink='0';img.style.background='#0a1611';}
  function ensure(a){if(a.dataset.thumbEnhanced)return;const href=a.getAttribute('href')||'';if(href.trim().charAt(0)==='#')return;const isYT=/youtu(?:\.be|be\.com)/.test(href);const inMedia=!!a.closest('#media-grid,.zero-media-grid,#tab-media');const inWalk=!!a.closest('#tab-walkaround');const videoLike=isYT||/video/i.test(a.className)||(a.textContent||'').match(/video|walkaround|cockpit|archive footage|documentary|engine start/i);if(!(inMedia||isYT||videoLike||(inWalk&&a.querySelector('img'))))return;let img=a.querySelector('img');const id=ytId(href);const hq=id?`https://img.youtube.com/vi/${id}/hqdefault.jpg`:'';const mq=id?`https://img.youtube.com/vi/${id}/mqdefault.jpg`:'';if(!img&&(inMedia||isYT||videoLike)){removeEmojiLead(a);img=document.createElement('img');img.alt=((a.textContent||'Reference video').trim().slice(0,90)||'Reference video thumbnail')+' thumbnail';img.src=hq||'video-thumb-fallback.png';installFallback(img,mq||'video-thumb-fallback.png');const compact=a.closest('#media-grid')&&!a.className.match(/card|zero|wa/);styleThumb(img,!!compact);a.insertBefore(img,a.firstChild);}else if(img){installFallback(img,mq||img.getAttribute('data-fallback')||'video-thumb-fallback.png');if(a.closest('#media-grid')&&!a.className.match(/card|zero|wa/))styleThumb(img,true);}a.dataset.thumbEnhanced='1';}
  function process(scope){(scope||document).querySelectorAll('#media-grid a,.zero-media-grid a,#tab-media a,#tab-walkaround a').forEach(ensure);}
  function boot(){process(document);document.querySelectorAll('#media-grid,#tab-media,#tab-walkaround,.zero-media-grid').forEach(n=>{try{new MutationObserver(()=>process(n)).observe(n,{childList:true,subtree:true});}catch(e){}});}
